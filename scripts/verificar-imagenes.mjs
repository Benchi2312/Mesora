import assert from 'node:assert/strict'
import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const leer = (ruta) => readFileSync(new URL(`../${ruta}`, import.meta.url), 'utf8')
const editor = leer('src/pages/admin/ImagenProductoEditor.tsx')
const menu = leer('src/pages/admin/MenuTab.tsx')
const helper = leer('src/lib/imagenesProducto.ts')
const dominio = leer('src/domain/restaurant/imagenProducto.ts')
const handler = leer('supabase/functions/cloudinary-producto/handler.ts')
const funcion = leer('supabase/functions/cloudinary-producto/index.ts')
const firmaCloudinary = leer('supabase/functions/cloudinary-producto/cloudinaryFirma.ts')
const migracion = leer('supabase/migrations/20261115072449_producto_imagen_public_id_cloudinary.sql')

assert.match(editor, /Usar enlace/)
assert.match(editor, /Subir archivo/)
assert.match(editor, /type="file"/)
assert.match(editor, /\.jpg,\.jpeg,\.png,\.webp,image\/jpeg,image\/png,image\/webp/)
assert.match(editor, /role="progressbar"/)
assert.match(editor, /Vista previa del producto/)
assert.match(editor, /Quitar imagen/)
assert.match(editor, /La imagen reemplazada se conserva hasta que se guarde/)
assert.match(editor, /5 MB/)
assert.match(menu, /imagen_public_id: m\.imagenPublicId/)
assert.match(menu, /validarUrlImagenProducto/)
assert.match(menu, /imagenesSubidasRef/)
assert.match(menu, /cerrarModalProducto/)
assert.match(helper, /auth\.getSession\(\)/)
assert.match(helper, /functions\/v1\/cloudinary-producto/)
assert.match(helper, /request\.upload\.onprogress/)
assert.doesNotMatch(helper, /CLOUDINARY_API_SECRET|VITE_CLOUDINARY/)
assert.match(dominio, /5 \* 1024 \* 1024/)
assert.match(dominio, /image\/jpeg.*image\/png.*image\/webp/s)
assert.match(dominio, /https:/)
assert.match(handler, /rol !== 'admin_restaurante'/)
assert.match(handler, /perfil\.activo !== true/)
assert.match(handler, /restaurante_id/)
assert.match(handler, /validarContenidoImagenProducto/)
assert.match(handler, /imagenEstaEnUso/)
assert.match(funcion, /CLOUDINARY_API_SECRET/)
assert.match(funcion, /CLOUDINARY_FOLDER/)
assert.match(funcion, /mesora\/products/)
assert.match(funcion, /api\.cloudinary\.com/)
assert.match(funcion, /parametrosCargaCloudinary\(CLOUD_FOLDER, publicId, timestamp\)/)
assert.doesNotMatch(funcion, /body\.set\('folder'/)
assert.match(firmaCloudinary, /asset_folder: carpetaActivos/)
assert.match(firmaCloudinary, /Object\.keys\(parametros\)\s*\.sort\(\)/)
assert.match(firmaCloudinary, /for \(const \[clave, valor\] of Object\.entries\(parametros\)\)/)
assert.doesNotMatch(firmaCloudinary, /body\.set\('folder'/)
assert.match(migracion, /add column if not exists imagen_public_id text/i)
assert.match(migracion, /comment on column public\.productos\.imagen_public_id/i)
assert.doesNotMatch(migracion, /not null/i)

const assets = fileURLToPath(new URL('../dist/assets', import.meta.url))
assert.equal(existsSync(assets), true, 'Ejecuta este verificador después del build para revisar el bundle')
const bundle = readdirSync(assets)
  .filter((archivo) => archivo.endsWith('.js'))
  .map((archivo) => readFileSync(join(assets, archivo), 'utf8'))
  .join('\n')
assert.doesNotMatch(bundle, /CLOUDINARY_API_SECRET|CLOUDINARY_API_KEY|CLOUDINARY_CLOUD_NAME|VITE_CLOUDINARY/)

console.log('Imágenes de producto: interfaz, validaciones, sesión, autorización, Cloudinary, migración y bundle sin secretos')
